#!/usr/bin/env python3
"""Render the robot's phrases (Kurdish Badini, Arabic, English) into
128x64 XBM bitmaps and write them to ../texts.h.

U8g2 cannot join Arabic-script letters or draw Kurdish letters such as
ڤ ێ ۆ ڕ ە, so the text is drawn here with proper shaping and stored as
pictures that the ESP32 only has to copy to the screen.

Needs Pillow built with libraqm (for right-to-left shaping).
Usage: python3 make_texts.py
"""
import os
from PIL import Image, ImageDraw, ImageFont, features

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
W, H = 128, 64

# Order must match the Phrase enum in ESP32_Talking_Robot.ino.
PHRASES = ["GREETING", "OBSTACLE", "CLEAR", "LANGUAGE"]

# Order must match the Language enum: Kurdish, Arabic, English.
TEXTS = {
    "KU": [("سلاڤ!", "ئەز ڕۆبۆتم"),
           ("ئاگەهدار بە!", "ڕێ گرتی یە"),
           ("ڕێ ڤالا یە", "ئەز دچم"),
           ("کوردی", "بادینی")],
    "AR": [("مرحباً!", "أنا روبوت"),
           ("انتبه!", "يوجد عائق"),
           ("الطريق مفتوح", "أنا ذاهب"),
           ("العربية", "")],
    "EN": [("Hello!", "I am a robot"),
           ("Watch out!", "Obstacle!"),
           ("Path is clear", "Let's go!"),
           ("English", "")],
}


def render(lines, rtl):
    img = Image.new("1", (W, H), 0)
    d = ImageDraw.Draw(img)
    lines = [t for t in lines if t]
    for size in (22, 20, 18, 16, 14):
        f = ImageFont.truetype(FONT, size)
        kw = {"direction": "rtl"} if rtl else {}
        if all(d.textlength(t, font=f, **kw) <= W - 2 for t in lines):
            break
    ys = [32] if len(lines) == 1 else [16, 48]
    for t, y in zip(lines, ys):
        d.text((W // 2, y), t, font=f, fill=1, anchor="mm", **kw)
    return img


def to_xbm(img):
    # XBM: rows top to bottom, 8 pixels per byte, least significant bit first.
    out = []
    px = img.load()
    for y in range(H):
        for xb in range(0, W, 8):
            b = 0
            for bit in range(8):
                if px[xb + bit, y]:
                    b |= 1 << bit
            out.append(b)
    return out


def main():
    if not features.check("raqm"):
        raise SystemExit("Pillow needs libraqm for Arabic/Kurdish shaping")
    here = os.path.dirname(os.path.abspath(__file__))
    preview = Image.new("1", (W * 4 + 12, H * 3 + 8), 0)
    c = ["// Generated by tools/make_texts.py - do not edit by hand.",
         "#pragma once", "#include <Arduino.h>", ""]
    names = []
    for li, (lang, rows) in enumerate(TEXTS.items()):
        for pi, lines in enumerate(rows):
            img = render(lines, rtl=(lang != "EN"))
            preview.paste(img, (pi * (W + 4), li * (H + 4)))
            name = f"txt_{lang}_{PHRASES[pi]}"
            names.append(name)
            data = to_xbm(img)
            c.append(f"// {' / '.join(t for t in lines if t)}")
            c.append(f"static const unsigned char {name}[] PROGMEM = {{")
            for i in range(0, len(data), 16):
                c.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
            c.append("};")
            c.append("")
    c.append("static const unsigned char* const TEXTS[3][4] = {")
    for li in range(3):
        c.append("  { " + ", ".join(names[li * 4:li * 4 + 4]) + " },")
    c.append("};")
    with open(os.path.join(here, "..", "texts.h"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(c) + "\n")
    preview.save(os.path.join(here, "preview.png"))


if __name__ == "__main__":
    main()
